/**
 * Universal translation retriever function.
 * Supports direct dictionary keys (e.g. 'nav.home') or plain text lookup.
 */
export function getTranslation(lang: Language, key: string, fallback?: string): string {
  if (!key) return fallback || '';
  
  // If English, return exact original string / fallback or English dictionary match
  if (lang === 'en') {
    const enDict = TRANSLATIONS['en'] || {};
    return fallback || enDict[key] || key;
  }

  const langDict = TRANSLATIONS[lang] || TRANSLATIONS['en'] || {};
  const enDict = TRANSLATIONS['en'] || {};

  // 1. Direct dictionary key match (e.g., 'nav.home' or 'Roads & Infrastructure')
  if (langDict[key]) {
    return langDict[key];
  }

  // 2. Trimmed key match
  const trimmedKey = key.trim();
  if (langDict[trimmedKey]) {
    return langDict[trimmedKey];
  }

  // 3. Fallback string match
  if (fallback) {
    const trimmedFallback = fallback.trim();
    if (langDict[trimmedFallback]) {
      return langDict[trimmedFallback];
    }
  }

  // 4. Reverse lookup matching English value or fallback text
  const keyLower = trimmedKey.toLowerCase();
  const fallbackLower = fallback ? fallback.trim().toLowerCase() : '';

  for (const [dictKey, enVal] of Object.entries(enDict)) {
    const enValLower = typeof enVal === 'string' ? enVal.toLowerCase() : '';
    if (
      dictKey === key || 
      dictKey === trimmedKey || 
      enValLower === keyLower ||
      (fallbackLower && enValLower === fallbackLower)
    ) {
      if (langDict[dictKey]) {
        return langDict[dictKey];
      }
    }
  }

  return fallback || langDict[key] || enDict[key] || key;
}
