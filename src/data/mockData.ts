export function getCentralDepartmentSummaries(
  complaintsList: Complaint[] = INITIAL_COMPLAINTS,
  assetsList: RecurringAssetInsight[] = RECURRING_ASSETS,
  rosters: Record<string, UserProfile[]> = DEPARTMENT_OFFICERS_ROSTER
): DepartmentSummary[] {
  const departmentNames = [
    'Stormwater Drainage',
    'Roads & Infrastructure',
    'Waste Management',
    'Water Supply',
    'Street Lighting',
  ];

  return departmentNames.map((deptName) => {
    const deptComplaints = complaintsList.filter((c) => c.department === deptName);
    const active = deptComplaints.filter((c) => c.status !== 'Resolved' && c.status !== 'Closed').length;
    const resolved = deptComplaints.filter((c) => c.status === 'Resolved' || c.status === 'Closed').length;
    const breaches = deptComplaints.filter((c) => c.slaStatus === 'Breached').length;
    const reopened = deptComplaints.filter((c) => c.status === 'Reopened' || (c.reopenedCount && c.reopenedCount > 0)).length;
    const total = deptComplaints.length;
    const resolutionRate = total > 0 ? Math.round((resolved / total) * 100) : 0;
    const deptOfficers = rosters[deptName] || [];

    let status: 'Stable' | 'Needs Attention' | 'Critical' = 'Stable';
    if (breaches >= 2 || (active >= 4 && resolutionRate < 35)) {
      status = 'Critical';
    } else if (breaches > 0 || reopened > 0 || active >= 3) {
      status = 'Needs Attention';
    }

    const descriptions: Record<string, string> = {
      'Stormwater Drainage': 'Stormwater culverts, flood mitigation, vacuum desilting, and hydraulic trunk maintenance.',
      'Roads & Infrastructure': 'Arterial corridors, structural pavement repairs, pothole clusters, and bituminous surfaces.',
      'Waste Management': 'Municipal solid waste logistics, commercial dumps, bin sanitation, and bio-waste collection.',
      'Water Supply': 'Potable water pipelines, distribution mains, underground pressure valves, and leak repairs.',
      'Street Lighting': 'Smart LED luminaire corridors, electrical feeder line maintenance, and nocturnal illumination.',
    };

    return {
      name: deptName,
      active,
      resolved,
      resolutionRate,
      slaBreaches: breaches,
      historicalReopened: reopened,
      status,
      headOfficerName: deptOfficers[0]?.name || 'Department Supervisor',
      description: descriptions[deptName] || 'Municipal department operations.',
      totalOfficers: deptOfficers.length,
    };
  });
}

export function getCentralOverviewStats(
  complaintsList: Complaint[] = INITIAL_COMPLAINTS,
  assetsList: RecurringAssetInsight[] = RECURRING_ASSETS
) {
  const activeCount = complaintsList.filter((c) => c.status !== 'Resolved' && c.status !== 'Closed').length;
  const resolvedCount = complaintsList.filter((c) => c.status === 'Resolved' || c.status === 'Closed').length;
  const totalCount = complaintsList.length;
  const slaBreaches = complaintsList.filter((c) => c.slaStatus === 'Breached').length;
  const recurringCount = assetsList.length;
  const resolutionRatePct = totalCount > 0 ? Math.round((resolvedCount / totalCount) * 100) : 0;

  return {
    activeCount,
    resolvedCount,
    totalCount,
    slaBreaches,
    recurringCount,
    resolutionRatePct,
  };
}

